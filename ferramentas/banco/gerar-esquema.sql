-- Gera o ESQUEMA COMPLETO do banco (estrutura, regras de acesso, funções, gatilhos) — SEM DADOS.
-- Rodar no SQL Editor do Supabase (projeto de produção) e salvar o resultado em supabase/esquema-completo.sql.
-- Serve para: montar o projeto de teste e reconstruir o banco se um dia precisar (o plano grátis não tem backup).
-- Não inclui: dados, segredos (integracao_segredo, push_config), agendamentos (pg_cron) nem contas de usuário.
with
tabs as (select c.oid, c.relname, c.relrowsecurity, c.relforcerowsecurity from pg_class c join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'public' and c.relkind = 'r'),
funcs as (select p.oid from pg_proc p join pg_namespace n on n.oid = p.pronamespace
          where n.nspname = 'public' and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')),
partes as (
  select 0 ord, '' k, $h$-- MOVER.IA — esquema completo (gerado por ferramentas/banco/gerar-esquema.sql). Sem dados.
set check_function_bodies = off;
create extension if not exists pgcrypto with schema extensions;
create extension if not exists "uuid-ossp" with schema extensions;
create extension if not exists pg_net with schema extensions;
create extension if not exists pg_cron;$h$ ddl
  union all
  select 1, t.typname, format('create type public.%I as enum (%s);', t.typname,
    (select string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder) from pg_enum e where e.enumtypid = t.oid))
  from pg_type t join pg_namespace n on n.oid = t.typnamespace where n.nspname = 'public' and t.typtype = 'e'
  union all
  select 2, c.relname, format('create sequence if not exists public.%I;', c.relname)
  from pg_class c join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'public' and c.relkind = 'S'
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'i') -- as das colunas "identity" a tabela cria sozinha
  union all
  select 3, t.relname, format(E'create table public.%I (\n%s\n);', t.relname,
    (select string_agg(format('  %I %s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
        case when a.attidentity = 'a' then ' generated always as identity' when a.attidentity = 'd' then ' generated by default as identity' else '' end,
        case when a.attnotnull then ' not null' else '' end), E',\n' order by a.attnum)
     from pg_attribute a where a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped))
  from tabs t
  union all
  select 4, p.oid::regprocedure::text, pg_get_functiondef(p.oid) || ';' from funcs f join pg_proc p on p.oid = f.oid
  union all
  select 5, t.relname || a.attname, format('alter table public.%I alter column %I set default %s;', t.relname, a.attname, pg_get_expr(d.adbin, d.adrelid))
  from tabs t join pg_attribute a on a.attrelid = t.oid join pg_attrdef d on d.adrelid = t.oid and d.adnum = a.attnum where a.attidentity = ''
  union all
  select case when co.contype = 'f' then 7 else 6 end, t.relname || co.conname,
    format('alter table public.%I add constraint %I %s;', t.relname, co.conname, pg_get_constraintdef(co.oid))
  from tabs t join pg_constraint co on co.conrelid = t.oid
  union all
  select 8, i.indexrelid::regclass::text, pg_get_indexdef(i.indexrelid) || ';'
  from tabs t join pg_index i on i.indrelid = t.oid where not exists (select 1 from pg_constraint co where co.conindid = i.indexrelid)
  union all
  select 9, t.relname || tg.tgname, pg_get_triggerdef(tg.oid) || ';' from tabs t join pg_trigger tg on tg.tgrelid = t.oid where not tg.tgisinternal
  union all
  select 10, t.relname, format('alter table public.%I enable row level security;', t.relname) || case when t.relforcerowsecurity then format(' alter table public.%I force row level security;', t.relname) else '' end
  from tabs t where t.relrowsecurity
  union all
  select case when p.schemaname = 'public' then 11 else 14 end, p.schemaname || p.tablename || p.policyname,
    format('create policy %I on %I.%I as %s for %s to %s%s%s;', p.policyname, p.schemaname, p.tablename, lower(p.permissive), lower(p.cmd), array_to_string(p.roles, ', '),
      case when p.qual is not null then E'\n  using (' || p.qual || ')' else '' end,
      case when p.with_check is not null then E'\n  with check (' || p.with_check || ')' else '' end)
  from pg_policies p where p.schemaname = 'public' or (p.schemaname = 'storage' and p.tablename = 'objects')
  union all
  select 12, '0', 'revoke all on all tables in schema public from anon, authenticated; revoke all on all sequences in schema public from anon, authenticated; revoke execute on all functions in schema public from public, anon, authenticated;'
  union all
  select 12, g.table_name || g.grantee, format('grant %s on public.%I to %I;', string_agg(g.privilege_type, ', '), g.table_name, g.grantee)
  from information_schema.role_table_grants g where g.table_schema = 'public' and g.grantee in ('anon', 'authenticated')
    and g.table_name in (select relname from tabs) group by g.table_name, g.grantee
  union all
  select 12, 'c' || cp.table_name || cp.grantee || cp.privilege_type, format('grant %s (%s) on public.%I to %I;', cp.privilege_type,
    string_agg(quote_ident(cp.column_name), ', ' order by cp.column_name), cp.table_name, cp.grantee)
  from information_schema.column_privileges cp where cp.table_schema = 'public' and cp.grantee in ('anon', 'authenticated')
    and not exists (select 1 from information_schema.role_table_grants g where g.table_schema = 'public' and g.table_name = cp.table_name
                    and g.grantee = cp.grantee and g.privilege_type = cp.privilege_type)
  group by cp.table_name, cp.grantee, cp.privilege_type
  union all
  select 12, 'f' || p.oid::regprocedure::text || r.rolname, format('grant execute on function %s to %s;', p.oid::regprocedure, case when r.oid is null then 'public' else quote_ident(r.rolname) end)
  from funcs f join pg_proc p on p.oid = f.oid cross join lateral aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) x
  left join pg_roles r on r.oid = x.grantee where x.privilege_type = 'EXECUTE' and (x.grantee = 0 or r.rolname in ('anon', 'authenticated'))
  union all
  select 12, 's' || c.relname || g.grantee, format('grant %s on sequence public.%I to %I;', string_agg(distinct x.privilege_type, ', '), c.relname, g.grantee)
  from pg_class c join pg_namespace n on n.oid = c.relnamespace cross join lateral aclexplode(c.relacl) x join pg_roles r on r.oid = x.grantee
  cross join lateral (select r.rolname::text as grantee) g where n.nspname = 'public' and c.relkind = 'S' and r.rolname in ('anon', 'authenticated') group by c.relname, g.grantee
  union all
  select 13, b.id, format('insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types) values (%L, %L, %L, %s, %L) on conflict (id) do nothing;',
    b.id, b.name, b.public, coalesce(b.file_size_limit::text, 'null'), b.allowed_mime_types)
  from storage.buckets b
  union all
  select 15, c.relname, format('alter sequence public.%I owned by public.%I.%I;', c.relname, t.relname, a.attname)
  from pg_class c join pg_depend d on d.objid = c.oid and d.deptype = 'a' join pg_class t on t.oid = d.refobjid
  join pg_attribute a on a.attrelid = t.oid and a.attnum = d.refobjsubid join pg_namespace n on n.oid = c.relnamespace where n.nspname = 'public' and c.relkind = 'S'
)
select ord, k, ddl from partes order by ord, k;
